#!/usr/bin/env node
// Keeps game content and reverse-engineering notes out of the repository.
//   node tools/guard/check_repo_content.mjs --staged            files in the index (pre-commit)
//   node tools/guard/check_repo_content.mjs --range A B          files changed from A to B (CI or by hand)
//   node tools/guard/check_repo_content.mjs --pre-push           reads git's pre-push lines on stdin
//   node tools/guard/check_repo_content.mjs --all                everything tracked at HEAD (known debt is only listed)
// Exit 1 when a file breaks a rule; known debt in baseline.txt is reported but does not fail. Install the hooks once with
//   git config core.hooksPath tools/hooks
import { execFileSync } from 'node:child_process';
import { readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const git = (...a) => execFileSync('git', a, { encoding: 'buffer', maxBuffer: 1 << 28 });
const gitText = (...a) => git(...a).toString('utf8');

// Rule 1: files and folders that come from a game dump, a console, or local reverse-engineering work.
const BAD_PATH = [
  /\.(nso|nro|nca|nsp|nsz|xci|xcz|npdm|keys|tik)$/i,
  /(^|\/)(prod|title)\.keys$/i,
  /(^|\/)(exefs|romfs|modding-docs|refs)\//i,
  /^(game|work|play)\//i,
];
// Rule 2: C and C++ the lifter wrote from the game's code (its first line says so).
const LIFTED = /^\s*(\/\*|\/\/)\s*generated by nxrecomp/i;
// Rule 3: reverse-engineering notes in documents. Guest addresses of a Switch 2 title (main 0x71..., sdk 0x75...) and the usual wording.
const NOTE_FILE = /\.(md|txt|rst)$/i;
const GUEST_ADDR = /\b0x(?:71|75)(?!0{8}\b)[0-9a-f]{8}\b/i;   // not the round module bases 0x7100000000 / 0x7500000000
const NOTE_WORDS = /\b(ghidra|decompil\w*|found by reading the sdk|sdk mapped at)\b/i;
// Rule 4: shared code knows no game, so no guest addresses outside the two game folders (and not in generated schemas).
const CODE_FILE = /\.(c|cc|cpp|cxx|h|hpp|py|rs|js|mjs|cmake)$/i;
const GAME_DIRS = /^(runtime|recomp)\/games\/[^/]+\//;

const baseline = new Set(readFileSync(join(here, 'baseline.txt'), 'utf8').split(/\r?\n/).map((l) => l.trim()).filter((l) => l && !l.startsWith('#')));

function violations(path, read) {
  const out = [];
  if (BAD_PATH.some((r) => r.test(path))) out.push({ rule: 'path', why: 'a game, console or local-notes path (dump, keys, exefs, romfs, modding-docs, refs)' });
  const text = (() => { try { return read().toString('utf8'); } catch { return null; } })();
  if (text === null) return out;
  const head = text.slice(0, 400);
  if (LIFTED.test(head) && !path.startsWith('recomp/nxrecomp/')) out.push({ rule: 'lifted', why: 'looks like C or C++ the lifter generated from the game code' });
  const lines = text.split(/\r?\n/);
  const hit = (re) => { const i = lines.findIndex((l) => re.test(l)); return i < 0 ? 0 : i + 1; };
  if (NOTE_FILE.test(path)) {
    const l = hit(GUEST_ADDR) || hit(NOTE_WORDS);
    if (l) out.push({ rule: 'notes', line: l, why: 'reverse-engineering notes (guest addresses or notes wording); keep them in the local, git-ignored modding-docs folder' });
  } else if (CODE_FILE.test(path) && !GAME_DIRS.test(path) && !/\.json$/i.test(path)) {
    const l = hit(GUEST_ADDR);
    if (l) out.push({ rule: 'shared-code', line: l, why: 'a game address in shared code (shared code knows no game)' });
  }
  return out;
}

function listed(mode, a, b) {
  if (mode === 'staged') return { read: (p) => git('show', `:${p}`), paths: gitText('diff', '--cached', '--name-only', '--diff-filter=AMR', '-z').split('\0').filter(Boolean) };
  if (mode === 'all') return { read: (p) => git('show', `HEAD:${p}`), paths: gitText('ls-tree', '-r', '--name-only', '-z', 'HEAD').split('\0').filter(Boolean) };
  return { read: (p) => git('show', `${b}:${p}`), paths: gitText('diff', '--name-only', '--diff-filter=AMR', '-z', a, b).split('\0').filter(Boolean) };
}

function scan(mode, a, b) {
  const { read, paths } = listed(mode, a, b);
  const bad = [], debt = [];
  for (const p of paths) {
    const v = violations(p, () => read(p));
    if (!v.length) continue;
    (baseline.has(p) ? debt : bad).push(...v.map((x) => ({ path: p, ...x })));
  }
  return { bad, debt, count: paths.length };
}

function main() {
  const [flag, x, y] = process.argv.slice(2);
  let runs = [];
  if (flag === '--staged') runs = [['staged']];
  else if (flag === '--all') runs = [['all']];
  else if (flag === '--range' && x && y) runs = [['range', x, y]];
  else if (flag === '--pre-push') {
    const zero = /^0+$/;
    for (const line of readFileSync(0, 'utf8').split(/\r?\n/).filter(Boolean)) {
      const [, local, , remote] = line.split(' ');
      if (!local || zero.test(local)) continue;                       // a deleted branch
      let base = remote && !zero.test(remote) ? remote : '';
      if (!base) { try { base = gitText('merge-base', local, 'origin/main').trim(); } catch { base = ''; } }
      runs.push(base ? ['range', base, local] : ['range', gitText('hash-object', '-t', 'tree', '/dev/null').trim(), local]);
    }
  } else { console.error('usage: check_repo_content.mjs --staged | --all | --range <from> <to> | --pre-push'); process.exit(2); }
  let failed = false;
  for (const r of runs) {
    const { bad, debt, count } = scan(...r);
    for (const d of debt) console.log(`known (baseline): ${d.path}${d.line ? ':' + d.line : ''}  [${d.rule}] ${d.why}`);
    for (const v of bad) console.log(`BLOCKED: ${v.path}${v.line ? ':' + v.line : ''}  [${v.rule}] ${v.why}`);
    if (bad.length) failed = true;
    else if (r[0] !== 'all') console.log(`repo content check: ${count} file(s) checked, nothing blocked`);
  }
  if (failed) {
    console.log('\nNothing was committed or pushed. Move the file out of the repository (notes go in modding-docs/, which is git-ignored), or ask the repo owner if the rule is wrong for this file.');
    process.exit(1);
  }
}
main();
